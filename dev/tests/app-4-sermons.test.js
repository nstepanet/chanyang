  a.click('#tabs [data-screen=sermons]');
  a.w.__chanyang.go('sermon', { sermonId: noSummary.id, playFrom: 0, outlineOpen: false });
  ok('요약 카드와 단추가 없음', !a.$('.sm') && !a.$('[data-act=playFrom]') && !!a.$('.player iframe') && !!a.$('#note'));
  ok('영상이 처음부터', !/start=/.test(a.$('.player iframe').src));
  a.click('#tabs [data-screen=home]'); a.click('.hero');
  ok('홈에서 최근 설교를 열면 처음부터, 흐름은 접힘', S.screen === 'sermon' && S.playFrom === 0 && !S.outlineOpen);

  console.log('\n[4] 나에게 맞는 말씀 찾기 (설교 탭)');
  a.click('#tabs [data-screen=sermons]');
  ok('찾기 칸, 말씀 찾기 단추, 마음 단추 6개, 휴대폰 밖으로 보내지 않는다는 안내', !!a.$('#need') && !!a.$('[data-act=findSermons]') && a.$$('[data-act=mood]').length === 6 && /어디에도 보내거나 저장하지 않습니다/.test(a.text()));
  ok('처음에는 추천 목록이 없음', !/이런 설교를 권해 드려요/.test(a.text()) && !a.$('.why'));
  a.click('[data-act=findSermons]');
  ok('빈칸으로 누르면 아무 일도 없음', !S.needDone && !/권해 드려요/.test(a.text()));
  a.type('#need', '요즘 아들 취업 때문에 걱정이 많아요'); a.click('[data-act=findSermons]');
